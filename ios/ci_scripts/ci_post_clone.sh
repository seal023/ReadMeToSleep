#!/bin/sh
set -e
set -x

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
cd "$REPO_DIR"

echo "PWD=$(pwd)"

# ---------------------------------------------------------------
# 重建 .env
# 本仓库的 .gitignore 忽略 .env，云端 checkout 后并不存在，
# 因此必须在这里用「Xcode Cloud 工作流 → Environment Variables」里
# 配置的值重新生成（建议全部标记为 secret）。
#
# 需要的变量：
#   EXPO_PUBLIC_AI_API_KEY          阿里云百炼 API Key（AI 生成故事）
#   EXPO_PUBLIC_AI_BASE_URL         百炼 MaaS 端点
#   EXPO_PUBLIC_TTS_BASE_URL        DashScope TTS 端点（预留）
#   EXPO_PUBLIC_VOICE_ENROLL_URL    声音克隆注册端点（预留）
#   EXPO_PUBLIC_VOICE_WORKSPACE_ID  百炼 workspace（预留）
#
# 未配置的变量会写成空串，应用层会自行降级（见 services/ai.ts 的说明）。
#
# ⚠️ 安全：上面开了 set -x（命令回显），若直接 echo 含变量的行，
#    Key 会被打进 Xcode Cloud 构建日志。故这里临时关闭回显。
# ---------------------------------------------------------------
set +x

MISSING=""
for v in EXPO_PUBLIC_AI_API_KEY EXPO_PUBLIC_AI_BASE_URL EXPO_PUBLIC_TTS_BASE_URL EXPO_PUBLIC_VOICE_ENROLL_URL EXPO_PUBLIC_VOICE_WORKSPACE_ID; do
  eval "val=\${$v:-}"
  if [ -z "$val" ]; then
    echo "WARN: env var not configured in Xcode Cloud workflow: $v"
    MISSING="$MISSING $v"
  fi
done
if [ -n "$MISSING" ]; then
  echo "WARN: missing vars:$MISSING -> AI features will fall back to built-in stories"
fi

{
  echo "# Generated by ci_post_clone.sh on Xcode Cloud. DO NOT COMMIT."
  echo "EXPO_PUBLIC_AI_API_KEY=${EXPO_PUBLIC_AI_API_KEY:-}"
  echo "EXPO_PUBLIC_AI_BASE_URL=${EXPO_PUBLIC_AI_BASE_URL:-}"
  echo "EXPO_PUBLIC_TTS_BASE_URL=${EXPO_PUBLIC_TTS_BASE_URL:-}"
  echo "EXPO_PUBLIC_VOICE_ENROLL_URL=${EXPO_PUBLIC_VOICE_ENROLL_URL:-}"
  echo "EXPO_PUBLIC_VOICE_WORKSPACE_ID=${EXPO_PUBLIC_VOICE_WORKSPACE_ID:-}"
} > .env

echo ".env generated successfully"
set -x

brew install node || true
node -v
npm -v

npm install

npx expo prebuild -p ios --clean --no-install

cd ios
pod install --repo-update

echo "=== DONE ==="