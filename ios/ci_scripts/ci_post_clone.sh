#!/bin/sh
set -e
set -x

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
cd "$REPO_DIR"

echo "PWD=$(pwd)"

# ---------------------------------------------------------------
# 重建 .env
# 本仓库的 .gitignore 忽略 .env，云端 checkout 后并不存在，
# 因此必须在这里用「Xcode Cloud 工作流 → Environment Variables」里
# 配置的值重新生成（建议全部标记为 secret）。
#
# 需要的变量：
#   EXPO_PUBLIC_AI_API_KEY          阿里云百炼 API Key（AI 生成故事）
#   EXPO_PUBLIC_AI_BASE_URL         百炼 MaaS 端点
#   EXPO_PUBLIC_TTS_BASE_URL        DashScope TTS 端点（预留）
#   EXPO_PUBLIC_VOICE_ENROLL_URL    声音克隆注册端点（预留）
#   EXPO_PUBLIC_VOICE_WORKSPACE_ID  百炼 workspace（预留）
#   EXPO_PUBLIC_SUPABASE_URL        Supabase 项目 URL（账号登录）
#   EXPO_PUBLIC_SUPABASE_ANON_KEY   Supabase anon key（公开可暴露，前端设计如此）
#
# 未配置的变量会写成空串，应用层会自行降级（见 services/ai.ts 的说明）。
#
# ⚠️ 安全：上面开了 set -x（命令回显），若直接 echo 含变量的行，
#    Key 会被打进 Xcode Cloud 构建日志。故这里临时关闭回显。
# ---------------------------------------------------------------
set +x

MISSING=""
for v in EXPO_PUBLIC_AI_API_KEY EXPO_PUBLIC_AI_BASE_URL EXPO_PUBLIC_TTS_BASE_URL EXPO_PUBLIC_VOICE_ENROLL_URL EXPO_PUBLIC_VOICE_WORKSPACE_ID EXPO_PUBLIC_SUPABASE_URL EXPO_PUBLIC_SUPABASE_ANON_KEY; do
  eval "val=\${$v:-}"
  if [ -z "$val" ]; then
    echo "WARN: env var not configured in Xcode Cloud workflow: $v"
    MISSING="$MISSING $v"
  fi
done
if [ -n "$MISSING" ]; then
  echo "WARN: missing vars:$MISSING -> AI features will fall back to built-in stories"
fi

# —— Secret 接收确认（脱敏：只打印存在性与长度，绝不打印明文值）——
# 注意：本段位于 set +x 区域内，命令本身不会被回显；且只输出名称与长度。
echo "=== Secret check (masked) ==="
for v in EXPO_PUBLIC_AI_API_KEY EXPO_PUBLIC_AI_BASE_URL EXPO_PUBLIC_TTS_BASE_URL EXPO_PUBLIC_VOICE_ENROLL_URL EXPO_PUBLIC_VOICE_WORKSPACE_ID EXPO_PUBLIC_SUPABASE_URL EXPO_PUBLIC_SUPABASE_ANON_KEY; do
  eval "val=\${$v:-}"
  if [ -z "$val" ]; then
    echo "SECRET_CHECK: $v = absent"
  else
    echo "SECRET_CHECK: $v = present (len=${#val})"
  fi
done
echo "=== Secret check done ==="

{
  echo "# Generated by ci_post_clone.sh on Xcode Cloud. DO NOT COMMIT."
  echo "EXPO_PUBLIC_AI_API_KEY=${EXPO_PUBLIC_AI_API_KEY:-}"
  echo "EXPO_PUBLIC_AI_BASE_URL=${EXPO_PUBLIC_AI_BASE_URL:-}"
  echo "EXPO_PUBLIC_TTS_BASE_URL=${EXPO_PUBLIC_TTS_BASE_URL:-}"
  echo "EXPO_PUBLIC_VOICE_ENROLL_URL=${EXPO_PUBLIC_VOICE_ENROLL_URL:-}"
  echo "EXPO_PUBLIC_VOICE_WORKSPACE_ID=${EXPO_PUBLIC_VOICE_WORKSPACE_ID:-}"
  echo "EXPO_PUBLIC_SUPABASE_URL=${EXPO_PUBLIC_SUPABASE_URL:-}"
  echo "EXPO_PUBLIC_SUPABASE_ANON_KEY=${EXPO_PUBLIC_SUPABASE_ANON_KEY:-}"
} > .env

echo ".env generated successfully"
set -x

# ---------------------------------------------------------------
# Node.js 获取（构建 72 的失败点，勿再退化成「只靠 brew」）
#
# 2026-11-01 构建 72 失败链路：
#   brew install node → Homebrew 自身需升级内置 portable-ruby
#   → 从 ghcr.io 拉包被限流/拦截 → "Failed to upgrade Homebrew Portable Ruby!"
#   → brew 完全不可用 → node 没装上 → `node -v` 报 command not found
#   → set -e 触发，脚本 exit 127，整个 Archive 失败。
#
# 现在改成三级兜底，任一级成功即可，且最脆弱的一级放最后：
#   1) 镜像自带 / 常见前缀里的 node（最快，零网络）
#   2) nodejs.org 官方 mac 二进制包直下（不经过 Homebrew，避开 ghcr.io）
#   3) brew install node（best-effort，失败只告警不中断）
# ---------------------------------------------------------------
node_ready() { command -v node >/dev/null 2>&1; }

if ! node_ready; then
  for p in /usr/local/bin /opt/homebrew/bin /opt/homebrew/opt/node/bin /usr/local/opt/node/bin; do
    if [ -x "$p/node" ]; then
      export PATH="$p:$PATH"
      echo "found node at $p"
      break
    fi
  done
fi

if ! node_ready; then
  # Node 22 LTS：满足 Expo SDK 57 / RN 0.86 的 >= 20 要求。
  # 版本号写死（不查 latest），保证下载地址长期可复现。
  NODE_VERSION="v22.11.0"
  case "$(uname -m)" in
    arm64) NODE_ARCH="arm64" ;;
    *)     NODE_ARCH="x64" ;;
  esac
  NODE_DIR="$HOME/.ci-node"
  echo "node not found -> downloading official binary $NODE_VERSION ($NODE_ARCH)"
  rm -rf "$NODE_DIR"
  mkdir -p "$NODE_DIR"
  curl -fsSL --retry 3 --retry-delay 2 --connect-timeout 20 \
    "https://nodejs.org/dist/${NODE_VERSION}/node-${NODE_VERSION}-darwin-${NODE_ARCH}.tar.gz" -o /tmp/node.tar.gz
  tar -xzf /tmp/node.tar.gz -C "$NODE_DIR" --strip-components=1
  export PATH="$NODE_DIR/bin:$PATH"
fi

if ! node_ready; then
  echo "node still missing -> last resort: brew (may be blocked by ghcr.io)"
  HOMEBREW_NO_AUTO_UPDATE=1 HOMEBREW_NO_INSTALL_CLEANUP=1 HOMEBREW_NO_ANALYTICS=1 \
    brew install node || echo "WARN: brew install node failed"
fi

if ! node_ready; then
  echo "ERROR: node unavailable, abort. Check nodejs.org connectivity or the image's node path"
  exit 1
fi

node -v
npm -v

npm install

npx expo prebuild -p ios --clean --no-install

cd ios
pod install --repo-update

echo "=== DONE ==="